import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.NEXOPS_PLAYWRIGHT_PATH || 'playwright-core')
const base = process.env.NEXOPS_TEST_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({executablePath:process.env.NEXOPS_CHROMIUM || '/usr/bin/chromium',headless:true,args:['--no-sandbox']})
const STORAGE = 'nexops_synthetic_operations_v1'
const futureDate = new Date(Date.now()+3*86400000).toISOString().slice(0,10)
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}})
  const errors = [], external = []
  page.on('pageerror',e => errors.push(e.message))
  page.on('request',r => { if (!r.url().startsWith(base) && !r.url().startsWith('data:')) external.push(r.url()) })
  const nav = name => page.getByRole('navigation').getByRole('button',{name,exact:true}).click()
  const english = async () => { if (await page.getByRole('button',{name:'アクショントラッカー',exact:true}).count()) await page.getByRole('button',{name:'EN / JP'}).click() }
  await page.goto(base+'/demo/operations?view=exceptions')
  await page.getByRole('heading',{name:'例外受信箱',exact:true}).waitFor()
  await english()
  await page.locator('.ops-row-link').first().click()
  let dialog = page.getByRole('dialog')
  await dialog.getByText('Create an action',{exact:true}).click()
  await dialog.getByLabel('Action description',{exact:true}).fill('UI Phase 2 partial shipment')
  await dialog.getByLabel('Action owner',{exact:true}).fill('UI Operator')
  await dialog.getByLabel('Action due date',{exact:true}).fill(futureDate)
  await dialog.getByRole('checkbox',{name:'Customer approval required',exact:true}).check()
  await dialog.getByRole('button',{name:'Create linked action',exact:true}).click()
  await dialog.getByRole('heading',{name:'Linked actions (2)',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  await page.locator('.ops-row-link').nth(1).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Existing action',{exact:true}).selectOption('DEMO-ACT-002')
  await dialog.getByRole('button',{name:'Link action',exact:true}).click()
  await dialog.getByRole('button',{name:'DEMO-ACT-002 · UI Phase 2 partial shipment',exact:true}).click()
  const action = page.locator('#DEMO-ACT-002')
  await action.waitFor()
  await action.getByLabel('Action status',{exact:true}).selectOption('In Progress')
  await action.getByRole('button',{name:'Save action',exact:true}).click()
  await action.getByRole('status').filter({hasText:'Customer approval'}).waitFor()
  await nav('Customer Decisions')
  const decision = page.locator('.ops-work-card').filter({has:page.getByRole('heading',{name:'UI Phase 2 partial shipment',exact:true})})
  for (const [value,expected] of [['Approve','Approved'],['Modify','Modified'],['Reject','Rejected'],['Defer','Deferred'],['Approve','Approved']]) {
    await decision.getByLabel('Customer decision',{exact:true}).selectOption(value)
    await decision.getByLabel('Decision reason',{exact:true}).fill(`UI review: ${value}`)
    if (value === 'Modify') await decision.getByLabel('Modified decision',{exact:true}).fill('UI partial shipment: 25 units')
    await decision.getByRole('button',{name:'Record decision',exact:true}).click()
    await decision.locator('strong').filter({hasText:new RegExp(`^${expected}$`)}).waitFor()
  }
  await nav('Decision History')
  assert.ok((await page.locator('.ops-workflow').textContent()).includes('UI partial shipment: 25 units'))
  await nav('Action Tracker')
  await action.getByLabel('Owner',{exact:true}).fill('UI Assigned Owner')
  await action.getByLabel('Action status',{exact:true}).selectOption('Resolved')
  await action.getByLabel('Resolution',{exact:true}).fill('UI demo receipt confirmed')
  await action.getByRole('button',{name:'Save action',exact:true}).click()
  await action.getByRole('status').filter({hasText:'Saved'}).waitFor()
  await nav('Weekly Operations Report')
  await page.getByRole('button',{name:'Save report baseline',exact:true}).click()
  assert.equal(await page.getByLabel('Previous report',{exact:true}).locator('option').count(),2)
  await nav('Supplier Monitoring')
  const supplier = page.locator('.ops-work-card').filter({hasText:'DEMO-PO-100'}).first()
  await supplier.getByLabel('Promised date',{exact:true}).fill(futureDate)
  await supplier.getByLabel('Expected date',{exact:true}).fill(futureDate)
  await supplier.getByLabel('Confirmed quantity',{exact:true}).fill('180')
  await supplier.getByLabel('Delay reason / update note',{exact:true}).fill('UI synthetic updated commitment')
  await supplier.getByLabel('Risk level',{exact:true}).selectOption('Low')
  await supplier.getByRole('button',{name:'Save monitoring update',exact:true}).click()
  await supplier.getByText(/Delay days: 0/).waitFor()
  await nav('Weekly Operations Report')
  await page.getByLabel('Previous report',{exact:true}).selectOption('DEMO-REPORT-001')
  assert.ok((await page.locator('.ops-report').textContent()).includes('suppliers: 0 added / 1 changed'))
  await page.evaluate(() => { window.print = () => { window.__printRequested = true } })
  await page.getByRole('button',{name:'Print report',exact:true}).click()
  assert.ok(await page.evaluate(() => window.__printRequested))
  await page.emulateMedia({media:'print'})
  assert.equal(await page.locator('.ops-report-controls').isVisible(),false)
  await page.pdf({path:'/tmp/nexops-phase2-report.pdf',format:'A4',printBackground:true})
  await page.emulateMedia({media:'screen'})
  await page.screenshot({path:'/tmp/nexops-phase2-report.png',fullPage:true})
  const state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)),STORAGE)
  assert.equal(state.data.actions.length,2)
  assert.equal(state.data.actions[1].exceptionIds.length,2)
  assert.equal(state.data.actions[1].resolution,'UI demo receipt confirmed')
  assert.equal(state.data.decisions[1].history.length,6)
  await page.reload()
  await page.getByRole('heading',{name:'週次運用レポート',exact:true}).first().waitFor()
  assert.ok((await page.evaluate(key => JSON.parse(localStorage.getItem(key)),STORAGE)).data.actions.some(a => a.resolution === 'UI demo receipt confirmed'))
  // Each route is directly loadable; customer scope applies to all phase-2 views.
  const headings = {actions:'アクショントラッカー',decisions:'顧客判断',history:'判断履歴',suppliers:'仕入先モニタリング',report:'週次運用レポート'}
  for (const [view,heading] of Object.entries(headings)) {
    await page.goto(base+`/demo/operations?view=${view}`)
    await page.getByRole('heading',{name:heading,exact:true}).first().waitFor()
    await page.screenshot({path:`/tmp/nexops-phase2-${view}.png`,fullPage:true})
    await page.getByLabel('顧客',{exact:true}).selectOption('demo-harbor')
    assert.ok(!(await page.locator('.ops-workflow,.ops-report').textContent()).includes('Northstar'))
    await page.setViewportSize({width:390,height:844})
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),view+' must fit mobile viewport')
    await page.setViewportSize({width:1440,height:1000})
  }
  assert.deepEqual(errors,[])
  assert.deepEqual(external,[])
  console.log('Phase 2 browser workflow passed: exception creation/linking, approval guard, all decisions, history, resolution, supplier update/recalculation, baseline comparison, print/PDF, persistence, five direct routes, customer scope, mobile, zero external requests/runtime errors.')
} finally { await browser.close() }

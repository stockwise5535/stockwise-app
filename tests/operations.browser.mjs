// Optional UI smoke suite. Supply a separately installed playwright-core path.
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.NEXOPS_PLAYWRIGHT_PATH || 'playwright-core')
const base = process.env.NEXOPS_TEST_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({ executablePath:process.env.NEXOPS_CHROMIUM || '/usr/bin/chromium', headless:true, args:['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport:{ width:1440, height:1000 } })
  const errors = []
  const requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => requests.push(request.url()))
  await page.goto(base + '/demo/operations')
  await page.getByRole('heading', { name:'TODAY', exact:true }).waitFor()
  assert.equal(await page.locator('tbody tr').count(), 34)
  assert.ok(!requests.some(url => /supabase|AuthContext|LegacyApplication/.test(url)), 'demo must not import or contact authentication')
  await page.getByRole('button', { name:'EN / JP' }).click()
  await page.getByRole('button', { name:/Exception Inbox/ }).click()
  assert.equal(await page.locator('tbody tr').count(), 35)
  await page.getByLabel('Customer', { exact:true }).selectOption('demo-north')
  assert.ok(await page.locator('tbody tr').count() > 0)
  assert.ok((await page.locator('tbody tr td:first-child').allTextContents()).every(s => s.includes('Northstar')))
  await page.getByLabel('Status', { exact:true }).selectOption('Resolved')
  assert.equal(await page.locator('tbody tr').count(), 1)
  await page.getByLabel('Severity', { exact:true }).selectOption('Critical')
  await page.getByRole('heading', { name:'No matching exceptions' }).waitFor()
  await page.getByRole('button', { name:'Clear filters' }).click()
  await page.locator('.ops-row-link').first().click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  await dialog.getByLabel('Owner', { exact:true }).fill('UI Test Operator')
  await dialog.getByLabel('Status', { exact:true }).selectOption('Investigating')
  await dialog.getByLabel('Due date (UTC)', { exact:true }).fill('2026-11-01')
  await dialog.getByRole('button', { name:'Save review' }).click()
  await dialog.getByText('Saved to this browser only.', { exact:true }).waitFor()
  assert.equal(await dialog.locator('.ops-history li').count(), 2)
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.ok(await page.evaluate(() => document.activeElement.classList.contains('ops-row-link')), 'closing detail restores queue focus')
  await page.reload()
  await page.getByRole('heading', { name:'TODAY', exact:true }).waitFor()
  assert.ok((await page.locator('tbody').textContent()).includes('UI Test Operator'))
  await page.setViewportSize({ width:390, height:844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'horizontal scroll must stay inside table')
  await page.screenshot({ path:'/tmp/nexops-mobile.png', fullPage:true })
  await page.setViewportSize({ width:1440, height:1000 })
  await page.screenshot({ path:'/tmp/nexops-today.png', fullPage:true })
  await page.goto(base + '/demo/operations?view=exceptions')
  await page.getByRole('heading', { name:'例外受信箱', exact:true }).waitFor()
  assert.equal(await page.locator('tbody tr').count(), 35)
  await page.evaluate(() => localStorage.setItem('nexops_synthetic_operations_v1', '{broken'))
  await page.reload()
  await page.getByRole('heading', { name:'例外受信箱', exact:true }).waitFor()
  assert.equal(await page.locator('tbody tr').count(), 35)
  assert.deepEqual(errors, [])
  console.log('Browser smoke passed: isolated demo, queue, combined filters, empty state, assignment/status/history, reload persistence, Escape/focus, mobile overflow, direct inbox route, corrupt-storage recovery; zero runtime errors.')
} finally { await browser.close() }
